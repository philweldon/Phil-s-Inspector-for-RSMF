#!/usr/bin/env python3
"""Regenerates src/Rsmf.Core/Resources/emoji_short_names.txt: emoji short names (":thumbsup:", ":smile:")
to the emoji they stand for. RSMF files write emoji in message text and reactions as short names.
Build-time only: needs `pip install emoji` (BSD 3-Clause). Nothing from that package ships except the names."""
import os, re, unicodedata
import emoji
from emoji import EMOJI_DATA

alias = {}
def add(name, ch):
    name = name.strip(':').strip()
    if name and re.fullmatch(r'[A-Za-z0-9_+\-]+', name):
        alias.setdefault(name.lower(), ch)

# Fully-qualified forms first, so a name such as "heart" gives the emoji-style character (with its selector).
items = sorted(EMOJI_DATA.items(), key=lambda kv: (0 if kv[1].get('status') == emoji.STATUS['fully_qualified'] else 1, kv[1].get('E', 99), kv[0]))
for ch, d in items:                                   # 1. established short names first
    for a in d.get('alias', []):
        add(a, ch)
for ch, d in items:                                   # 2. descriptive names, then names from the Unicode character name
    if d.get('status') != emoji.STATUS['fully_qualified']:
        continue
    if d.get('en'):
        add(d['en'], ch)
    base = ch.replace('️', '')
    if len(base) == 1:
        try:
            add(unicodedata.name(base).lower().replace(' ', '_'), ch)
        except ValueError:
            pass

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'Rsmf.Core', 'Resources', 'emoji_short_names.txt')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Emoji short names -> emoji. Generated by tools/make-emoji-names.py from the "emoji" Python package (BSD 3-Clause) and Unicode character names.\n')
    for k in sorted(alias):
        f.write(k + '\t' + alias[k] + '\n')
print(len(alias), 'names')
